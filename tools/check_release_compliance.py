def validate_release_component_payload(release_dir: Path) -> list[str]:
    issues: list[str] = []
    manifest_path = release_dir / COMPONENT_MANIFEST
    if not manifest_path.is_file():
        return [f"missing required release metadata: {COMPONENT_MANIFEST}"]
    issues.extend(validate_component_manifest(manifest_path, repo_root=release_dir, cmake_text=""))
    try:
        sbom = json.loads((release_dir / SBOM_FILE).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        issues.append(f"invalid release SBOM: {error}")
        return sorted(set(issues))
    distributed = {component["name"] for component in json.loads(manifest_path.read_text(encoding="utf-8"))["components"] if component["distributed"]}
    sbom_names = {component.get("name") for component in sbom.get("components", [])}
    if distributed - sbom_names:
        issues.append(f"SBOM missing distributed components: {', '.join(sorted(distributed - sbom_names))}")
    for component in json.loads(manifest_path.read_text(encoding="utf-8"))["components"]:
        for expected in component["distribution_paths"]:
            # HarkenSearch.exe is a build product, while this metadata-focused release
            # validation only requires separately staged dependencies to exist.
            if component["distributed"] and expected not in {"Aris.exe", "HarkenSearch.exe"} and not (release_dir / expected).exists():
                issues.append(f"{component['name']}: declared release path missing: {expected}")
        if not component["distributed"]:
            for forbidden in ("PTSLC_CPP.dll",):
                if forbidden in component["name"] or component["name"] == "Avid PTSL SDK":
                    if (release_dir / forbidden).exists():
                        issues.append(f"{component['name']}: forbidden default SDK payload present: {forbidden}")
    return sorted(set(issues))



def should_skip(relative_path: Path, skip_paths: tuple[Path, ...] = SKIP_PATHS) -> bool:
    return (
        "__pycache__" in relative_path.parts
        or "node_modules" in relative_path.parts
        or any(
            relative_path == skip_path or skip_path in relative_path.parents
            for skip_path in skip_paths
        )
        or any(relative_path.match(pattern) for pattern in SKIP_GLOBS)
    )


def iter_scan_files(
    repo_root: Path = DEFAULT_REPO_ROOT,
    scan_targets: tuple[str, ...] = SCAN_TARGETS,
    skip_paths: tuple[Path, ...] = SKIP_PATHS,
) -> list[Path]:
    files: list[Path] = []
    tracked = tracked_paths(repo_root)
    for target in scan_targets:
        path = repo_root / target
        if not path.exists():
            continue
        candidates = [path] if path.is_file() else path.rglob("*")
        for child in candidates:
            if not child.is_file():
                continue
            relative_path = child.relative_to(repo_root)
            # Real gates never inspect local drafts. Unit fixtures intentionally
            # have no Git repository, where scanning the fixture tree remains useful.
            if tracked is not None and relative_path not in tracked:
                continue
            if should_skip(relative_path, skip_paths):
                continue
            files.append(child)
    return sorted(files, key=lambda path: path.relative_to(repo_root).as_posix())


def _scan_text_files(
    files: list[Path],
    root: Path,
    normalized_markers: tuple[tuple[str, str], ...],
    *,
    allow_contexts: bool,
) -> list[tuple[Path, int, str]]:
    violations: list[tuple[Path, int, str]] = []
    for file_path in files:
        relative_path = file_path.relative_to(root)
        text = file_path.read_text(encoding="utf-8", errors="replace")
        for line_number, line in enumerate(text.splitlines(), start=1):
            normalized_line = line.casefold()
            for marker, normalized_marker in normalized_markers:
                if normalized_marker not in normalized_line:
                    continue
                violations.append((relative_path, line_number, marker))
    return sorted(violations, key=lambda item: (item[0].as_posix(), item[1], item[2]))



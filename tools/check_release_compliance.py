def find_release_provenance_violations(release_dir: Path) -> list[tuple[Path, int, str]]:
    """Check text and native binaries; the position is a byte offset, not a line."""
    violations = []
    for path in sorted(release_dir.rglob("*")):
        if not path.is_file() or "LICENSES" in path.relative_to(release_dir).parts:
            continue
        data = path.read_bytes().lower()
        for marker in RELEASE_PROVENANCE_MARKERS:
            offsets = [data.find(marker.casefold().encode(encoding))
                       for encoding in ("utf-8", "utf-16-le")]
            found = [offset for offset in offsets if offset >= 0]
            if found:
                violations.append((path.relative_to(release_dir), min(found), marker))
    return violations



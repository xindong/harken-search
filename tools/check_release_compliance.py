def find_license_directory_issues(license_dir: Path) -> list[str]:
    issues: list[str] = []
    if not license_dir.exists():
        return [f"missing license bundle directory: {license_dir.as_posix()}"]
    if not license_dir.is_dir():
        return [f"license bundle path is not a directory: {license_dir.as_posix()}"]

    readme_path = license_dir / "README.md"
    if not readme_path.exists():
        issues.append(f"missing license bundle index: {readme_path.as_posix()}")

    actual_files = [
        path for path in license_dir.iterdir()
        if path.is_file() and path.name.casefold() != "readme.md"
    ]
    if not actual_files:
        issues.append(f"license bundle is placeholder-only: {license_dir.as_posix()}")
    readme_text = readme_path.read_text(encoding="utf-8", errors="replace") if readme_path.exists() else ""
    for file_name in REQUIRED_LICENSE_FILES:
        path = license_dir / file_name
        if not path.is_file():
            issues.append(f"missing required license file: {file_name}")
        if readme_text and file_name not in readme_text:
            issues.append(f"license bundle index missing entry: {file_name}")
    return issues


def hash_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def parse_binary_provenance(provenance_path: Path) -> dict[str, str]:
    hashes: dict[str, str] = {}
    text = provenance_path.read_text(encoding="utf-8", errors="replace")
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|"):
            continue
        cells = [cell.strip() for cell in stripped.split("|")[1:-1]]
        if len(cells) < 7:
            continue
        artifact = cells[0].strip("`")
        sha256 = cells[6].strip("`")
        if artifact in {"Artifact", "---"}:
            continue
        if artifact:
            hashes[artifact] = sha256
    return hashes


def iter_release_text_files(release_dir: Path) -> list[Path]:
    files: list[Path] = []
    for child in release_dir.rglob("*"):
        if not child.is_file():
            continue
        if "LICENSES" in child.parts:
            continue
        if child.suffix.lower() not in RELEASE_TEXT_EXTENSIONS and child.name != "LICENSE":
            continue
        files.append(child)
    return sorted(files)


def find_release_bundle_text_violations(release_dir: Path) -> list[tuple[Path, int, str]]:
    return _scan_text_files(
        iter_release_text_files(release_dir),
        release_dir,
        NORMALIZED_RUNTIME_MARKERS,
        allow_contexts=False,
    )


def validate_release_dir(release_dir: Path) -> list[str]:
    issues: list[str] = []
    if not release_dir.exists():
        return [f"release directory does not exist: {release_dir.as_posix()}"]
    if not release_dir.is_dir():
        return [f"release path is not a directory: {release_dir.as_posix()}"]

    for name in REQUIRED_RELEASE_METADATA:
        target = release_dir / name
        if not target.exists():
            issues.append(f"missing required release metadata: {name}")

    issues.extend(find_license_directory_issues(release_dir / "LICENSES"))

    for pattern in RELEASE_FORBIDDEN_GLOBS:
        for candidate in release_dir.rglob(pattern):
            issues.append(
                f"forbidden release artifact present: {candidate.relative_to(release_dir).as_posix()}"
            )

    provenance_path = release_dir / "BINARY_PROVENANCE.md"
    if provenance_path.exists():
        expected_hashes = parse_binary_provenance(provenance_path)
        for artifact in RELEASE_HASH_ARTIFACTS:
            artifact_path = release_dir / artifact
            if artifact not in expected_hashes:
                issues.append(f"missing SHA-256 entry for {artifact} in BINARY_PROVENANCE.md")
                continue
            if not artifact_path.exists():
                issues.append(f"release bundle missing artifact declared in BINARY_PROVENANCE.md: {artifact}")
                continue
            actual_hash = hash_file(artifact_path)
            expected_hash = expected_hashes[artifact].casefold()
            if actual_hash.casefold() != expected_hash:
                issues.append(
                    f"SHA-256 mismatch for {artifact}: expected {expected_hash}, got {actual_hash}"
                )
    else:
        issues.append("missing required release metadata: BINARY_PROVENANCE.md")

    issues.extend(validate_release_component_payload(release_dir))
    issues.extend(
        f"forbidden provenance/product marker in release bundle: {path.as_posix()}:{offset}: {marker}"
        for path, offset, marker in find_release_provenance_violations(release_dir)
    )

    for relative_path, line_number, marker in find_release_bundle_text_violations(release_dir):
        issues.append(
            f"forbidden runtime-network marker in release bundle: {relative_path.as_posix()}:{line_number}: {marker}"
        )

    return sorted(set(issues))


def run(
    repo_root: Path = DEFAULT_REPO_ROOT,
    scan_targets: tuple[str, ...] = SCAN_TARGETS,
    skip_paths: tuple[Path, ...] = SKIP_PATHS,
) -> int:
    violations = find_violations(
        repo_root=repo_root,
        scan_targets=scan_targets,
        skip_paths=skip_paths,
    )
    test_violations = find_test_source_violations(repo_root=repo_root)
    tool_violations = find_tool_source_violations(repo_root=repo_root)
    runtime_network_violations = find_runtime_network_violations(repo_root=repo_root)
    product_brand_violations = find_product_brand_violations(repo_root)
    private_file_issues = find_private_research_file_issues(repo_root)
    license_issues = find_license_directory_issues(repo_root / "LICENSES")
    manifest_issues = validate_component_manifest(repo_root / COMPONENT_MANIFEST, repo_root=repo_root)
    build_policy_issues = validate_default_build_policy(repo_root)
    version_issues = validate_product_version_consistency(repo_root)

    if (
        violations
        or test_violations
        or tool_violations
        or runtime_network_violations
        or product_brand_violations
        or private_file_issues
        or license_issues
        or manifest_issues
        or build_policy_issues
        or version_issues
    ):
        print("PUBLIC RELEASE COMPLIANCE CHECK FAILED")
        for relative_path, line_number, marker in violations + test_violations + tool_violations + product_brand_violations:
            print(f" - {relative_path.as_posix()}:{line_number}: {marker}")
        for relative_path, line_number, marker in runtime_network_violations:
            print(f" - {relative_path.as_posix()}:{line_number}: forbidden runtime-network marker {marker}")
        for issue in private_file_issues + license_issues + manifest_issues + build_policy_issues + version_issues:
            print(f" - {issue}")
        return 1

    print("PUBLIC RELEASE COMPLIANCE CHECK PASSED")
    print("No forbidden provenance markers, runtime DiceBear API literals, or license-bundle gaps found.")
    return 0


def run_release_dir(release_dir: Path) -> int:
    issues = validate_release_dir(release_dir)
    if issues:
        print("RELEASE BUNDLE COMPLIANCE CHECK FAILED")
        for issue in issues:
            print(f" - {issue}")
        return 1

    print("RELEASE BUNDLE COMPLIANCE CHECK PASSED")
    print("Release bundle metadata, exclusions, DiceBear runtime guards, and binary hashes all match policy.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Check Aris public-release compliance.")
    parser.add_argument(
        "--release-dir",
        type=Path,
        help="Validate a built public-release output directory instead of source-tree text surfaces.",
    )
    args = parser.parse_args(argv)

    if args.release_dir is not None:
        return run_release_dir(args.release_dir.resolve())
    return run()


if __name__ == "__main__":
    sys.exit(main())

def tracked_paths(repo_root: Path) -> set[Path] | None:
    """Return Git-tracked paths, or None for isolated unit-test fixtures."""
    completed = subprocess.run(
        ["git", "-C", str(repo_root), "ls-files", "-z"],
        check=False,
        capture_output=True,
    )
    if completed.returncode:
        return None
    return {Path(entry.decode("utf-8")) for entry in completed.stdout.split(b"\0") if entry}


def validate_component_manifest(
    manifest_path: Path,
    *,
    repo_root: Path = DEFAULT_REPO_ROOT,
    cmake_text: str | None = None,
) -> list[str]:
    issues: list[str] = []
    try:
        payload = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        return [f"cannot load third-party component manifest: {error}"]
    components = payload.get("components") if isinstance(payload, dict) else None
    if not isinstance(components, list) or not components:
        return ["third-party component manifest has no components"]
    policy = payload.get("policy")
    related_work_items = policy.get("related_work_items") if isinstance(policy, dict) else None
    if not isinstance(related_work_items, list) or "RQ-20260803-13" not in related_work_items:
        issues.append("component manifest policy.related_work_items must include RQ-20260803-13")
    notices_path = repo_root / "THIRD_PARTY_NOTICES.md"
    notices_text = notices_path.read_text(encoding="utf-8") if notices_path.is_file() else ""
    cmake = cmake_text if cmake_text is not None else (repo_root / "CMakeLists.txt").read_text(encoding="utf-8", errors="replace")
    seen: set[str] = set()
    for index, component in enumerate(components, start=1):
        prefix = f"component #{index}"
        if not isinstance(component, dict):
            issues.append(f"{prefix} is not an object")
            continue
        missing = []
        for field in REQUIRED_COMPONENT_FIELDS:
            if field not in component:
                missing.append(field)
                continue
            value = component[field]
            if value in (None, ""):
                missing.append(field)
            elif field in {"license_files", "notice_files", "cmake_markers"} and value == []:
                missing.append(field)
            elif field == "distribution_obligation" and not isinstance(value, dict):
                missing.append(field)
        if missing:
            issues.append(f"{prefix} missing required fields: {', '.join(missing)}")
            continue
        name = component["name"]
        obligation = component["distribution_obligation"]
        missing_obligation = [
            field
            for field in REQUIRED_DISTRIBUTION_OBLIGATION_FIELDS
            if field not in obligation or obligation[field] in (None, "")
        ]
        if missing_obligation:
            issues.append(
                f"{name}: distribution_obligation missing required fields: {', '.join(missing_obligation)}"
            )
        else:
            for boolean_field in ("copyleft", "commercial_restriction", "source_offer_required"):
                if not isinstance(obligation[boolean_field], bool):
                    issues.append(f"{name}: distribution_obligation.{boolean_field} must be a boolean")
            link_mode = obligation["link_mode"]
            if link_mode not in ALLOWED_LINK_MODES:
                issues.append(f"{name}: unknown link_mode: {link_mode}")
            if obligation["copyleft"] is True and component["distributed"]:
                issues.append(f"{name}: copyleft component must not be distributed")
            if (
                obligation["source_offer_required"] is True
                and component["distributed"]
                and not str(obligation.get("source_offer") or "").strip()
            ):
                issues.append(
                    f"{name}: source_offer_required with distributed=true requires a source_offer description"
                )
        if name in seen:
            issues.append(f"duplicate component name: {name}")
        seen.add(name)
        if name not in notices_text:
            issues.append(f"{name}: exact component name is missing from THIRD_PARTY_NOTICES.md")
        category = component["policy_category"]
        if category not in ALLOWED_POLICY_CATEGORIES:
            issues.append(f"{name}: unreviewed policy category: {category}")
        expression = component["license_expression"]
        allowed_categories = REVIEWED_LICENSE_EXPRESSIONS.get(expression)
        if allowed_categories is None:
            issues.append(f"{name}: unknown license expression is not reviewed: {expression}")
        elif category not in allowed_categories:
            issues.append(f"{name}: license expression {expression} is incompatible with policy category {category}")
        if category == "reviewed-commercial" and (not component["manual_approval_required"] or not component["approval_reference"]):
            issues.append(f"{name}: commercial redistribution requires a manual approval reference")
        if category.startswith("excluded-") and component["distributed"]:
            issues.append(f"{name}: default release must not distribute excluded component")
        for relative in component["license_files"] + component["notice_files"]:
            if not any((repo_root / candidate).is_file() for candidate in mapped_notice_candidates(relative)):
                issues.append(f"{name}: missing license or NOTICE mapping file: {relative}")
        cmake_search = cmake
        if cmake:
            extra_files = [
                repo_root / "CMakeLists.txt",
                repo_root / "THIRD_PARTY_NOTICES.md",
                repo_root / "reaper_extension" / "CMakeLists.txt",
                repo_root / "src" / "ed25519" / "tweetnacl.c",
                repo_root / "thirdparty" / "xxhash.h",
                repo_root / "thirdparty" / "nlohmann_json.hpp",
                repo_root / "thirdparty" / "miniaudio.h",
                repo_root / "thirdparty" / "stb_image.h",
                repo_root / "thirdparty" / "lucide" / "lucide.ttf",
                repo_root / "thirdparty" / "imgui",
                repo_root / "thirdparty" / "ixwebsocket" / "third_party" / "cli11",
                repo_root / "thirdparty" / "ixwebsocket" / "third_party" / "cpp-linenoise",
                repo_root / "thirdparty" / "ixwebsocket" / "third_party" / "msgpack11",
            ]
            extra_text = []
            for extra in extra_files:
                extra_text.append(extra.as_posix().replace("\\", "/"))
                extra_text.append(extra.relative_to(repo_root).as_posix() if extra.exists() or extra.is_relative_to(repo_root) else extra.name)
            cmake_search = cmake + "\n" + "\n".join(extra_text)
        for marker in component["cmake_markers"]:
            marker_path = repo_root / marker
            if cmake_search and marker not in cmake_search and not marker_path.exists():
                issues.append(f"{name}: CMake/source marker is absent: {marker}")
    for required_name in ("aubio", "Avid PTSL SDK"):
        if required_name not in seen:
            issues.append(f"component manifest missing controlled SDK entry: {required_name}")
    return sorted(set(issues))



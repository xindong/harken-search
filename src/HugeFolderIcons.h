inline void Draw(ImDrawList* drawList, ImVec2 center, float size, bool open, ImU32 color) {
    const float scale = size / 24.0f;
    const auto stroke = [&](const auto& points, bool closed) {
        for (const ImVec2& point : points)
            drawList->PathLineTo(ImVec2(center.x + (point.x - 12.0f) * scale,
                                        center.y + (point.y - 12.0f) * scale));
        drawList->PathStroke(color, closed ? ImDrawFlags_Closed : ImDrawFlags_None, 1.5f * scale);
    };
    if (open) {
        stroke(OpenFront, true);
        stroke(OpenBack, false);
        drawList->AddCircleFilled(ImVec2(center.x + 8.0f * scale, center.y - 3.0f * scale), 0.75f * scale, color);
    } else {
        stroke(Closed, true);
    }
}
